const dictionaries: Record<Lang, Record<string, string>> = { zh, en }

/** 归一化语言值。 */
function normalizeLang(value: string | null | undefined): Lang | null {
  return value === 'zh' || value === 'en' ? value : null
}

/** 当前语言：读 localStorage，默认中文。 */
export function getLang(): Lang {
  try {
    if (typeof localStorage === 'undefined') return 'zh'
    return normalizeLang(localStorage.getItem(LANG_STORAGE_KEY)) ?? 'zh'
  } catch {
    return 'zh'
  }
}

/** 设置语言：持久化 + 更新 <html lang> + 通知其他订阅者。 */
export function setLang(lang: Lang): void {
  const next = normalizeLang(lang) ?? 'zh'
  try {
    localStorage.setItem(LANG_STORAGE_KEY, next)
  } catch {
    // 隐私模式/配额不足：静默降级
  }
  try {
    if (typeof document !== 'undefined') document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
    if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: next }))
  } catch {
    // 非浏览器环境
  }
}

/** 翻译（缺失时回退中文，再回退 key 本身）。 */
export function translate(key: string, vars?: Record<string, string | number>, lang: Lang = getLang()): string {
  const raw = dictionaries[lang][key] ?? zh[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

/** 与当前语言无关的便捷 t（读取 getLang()）。 */
export function t(key: string, vars?: Record<string, string | number>): string {
  return translate(key, vars, getLang())
}

/** 语言相关 Intl locale。 */
export function localeOf(lang: Lang): string {
  return lang === 'zh' ? 'zh-CN' : 'en-GB'
}

/** React hook：首帧同步读 localStorage，避免中文闪一下。 */
export function useI18n(): {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
} {
  const [lang, setLangState] = useState<Lang>(() => getLang())
  useEffect(() => {
    try { document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en' } catch { /* ignore */ }
    const onChange = () => setLangState(getLang())
    window.addEventListener(LANG_EVENT, onChange)
    window.addEventListener('storage', onChange)
    return () => {
      window.removeEventListener(LANG_EVENT, onChange)
      window.removeEventListener('storage', onChange)
    }
  }, [lang])
  const change = (next: Lang) => {
    setLang(next)
    setLangState(getLang())
  }
  const translateFn = useMemo(
    () => (key: string, vars?: Record<string, string | number>) => translate(key, vars, lang),
    [lang],
  )
  return { lang, setLang: change, t: translateFn }
}
